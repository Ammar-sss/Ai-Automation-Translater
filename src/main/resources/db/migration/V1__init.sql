-- =============================================================================
-- 1. ROLES & USERS TABLES
-- =============================================================================
CREATE TABLE roles
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role_name VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uc_roles_rolename UNIQUE (role_name)
);

CREATE TABLE users
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username           VARCHAR(255)                            NOT NULL,
    email              VARCHAR(255)                            NOT NULL,
    password           VARCHAR(72)                             NOT NULL,
    enabled            BOOLEAN                                 NOT NULL DEFAULT TRUE,
    failed_attempts    INTEGER                                 NOT NULL DEFAULT 0,
    lock_until         TIMESTAMP(6) WITH TIME ZONE,
    last_login_attempt TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uc_users_email UNIQUE (email)
);

CREATE TABLE user_roles
(
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_userol_on_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_userol_on_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);

CREATE TABLE refresh_tokens
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    token             VARCHAR(255)                            NOT NULL,
    user_email        VARCHAR(255)                            NOT NULL,
    expiry_date       TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    revoked           BOOLEAN                                 NOT NULL DEFAULT FALSE,
    revoked_date      TIMESTAMP(6) WITH TIME ZONE,
    replaced_by_token VARCHAR(255),
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uc_refresh_tokens_token UNIQUE (token)
);

CREATE INDEX idx_refresh_tokens_user_email ON refresh_tokens (user_email);

-- =============================================================================
-- 2. VOCABULARY & TRANSLATION TABLES
-- =============================================================================
CREATE TABLE terms
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    word_term VARCHAR(255)                            NOT NULL,
    user_id   BIGINT                                  NOT NULL,
    CONSTRAINT pk_terms PRIMARY KEY (id),
    CONSTRAINT fk_terms_on_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uc_user_term UNIQUE (user_id, word_term)
);

CREATE TABLE term_definitions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    word_definition VARCHAR(255)                            NOT NULL,
    term_id         BIGINT                                  NOT NULL,
    CONSTRAINT pk_term_definitions PRIMARY KEY (id),
    CONSTRAINT fk_term_definitions_on_term FOREIGN KEY (term_id) REFERENCES terms (id) ON DELETE CASCADE
);

CREATE TABLE examples
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    example_sentence VARCHAR(255)                            NOT NULL,
    term_id          BIGINT                                  NOT NULL,
    CONSTRAINT pk_examples PRIMARY KEY (id),
    CONSTRAINT fk_examples_on_term FOREIGN KEY (term_id) REFERENCES terms (id) ON DELETE CASCADE
);

CREATE TABLE example_definitions
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    example_definition VARCHAR(255)                            NOT NULL,
    term_id            BIGINT                                  NOT NULL,
    CONSTRAINT pk_example_definitions PRIMARY KEY (id),
    CONSTRAINT fk_example_definitions_on_term FOREIGN KEY (term_id) REFERENCES terms (id) ON DELETE CASCADE
);

