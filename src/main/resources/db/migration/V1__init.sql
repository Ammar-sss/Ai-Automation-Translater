CREATE TABLE roles
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role_name VARCHAR(255) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uc_roles_rolename UNIQUE (role_name)
);

CREATE TABLE users
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username           VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL,
    password           VARCHAR(72)  NOT NULL,
    enabled            BOOLEAN      NOT NULL,
    failed_attempts    INTEGER      NOT NULL,
    lock_until         TIMESTAMP(6) WITH TIME ZONE,
    last_login_attempt TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uc_users_email UNIQUE (email)
);

CREATE TABLE user_roles
(
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_userol_on_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_userol_on_role FOREIGN KEY (role_id) REFERENCES roles (id)
);

CREATE TABLE refresh_tokens
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    token             VARCHAR(255) NOT NULL,
    user_email        VARCHAR(255) NOT NULL,
    expiry_date       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked           BOOLEAN      NOT NULL,
    revoked_date      TIMESTAMP(6) WITH TIME ZONE,
    replaced_by_token VARCHAR(255),
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uc_refresh_tokens_token UNIQUE (token)
);

CREATE INDEX idx_refresh_tokens_user_email ON refresh_tokens (user_email);

